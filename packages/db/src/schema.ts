/** Column helpers so the same shape is not retyped (and mistyped) on 14 tables. */
const id = () =>
  text("id")
    .primaryKey()
    .$defaultFn(() => randomUUID());
const now = () => sql`(unixepoch())`;
/** Renders a value list for a CHECK. The values are compile-time constants, never input. */
const inList = (values: readonly string[]) => sql.raw(values.map((v) => `'${v}'`).join(", "));

