/**
 * Single source of truth for the whole platform (web, Telegram bot, Bale bot, admin panels).
 *
 * Multi-tenancy: every business table carries `tenant_id`. Application code must always
 * query through the tenant-scoped repositories in @arayeshgar/core (never raw cross-tenant).
 * Keeping everything keyed by tenant_id is what makes "extract one big customer to their own
 * server" a plain `INSERT INTO ... SELECT ... WHERE tenant_id = X` later.
 *
 * Storage: SQLite (WAL, busy_timeout=5000), per §9ب of PLATFORM.md — the shared backup,
 * `Ops → db-query` and the shared dashboard all assume a `data/*.db` SQLite file.
 *
 * Time: every instant is an INTEGER of whole seconds since the epoch, which is both what
 * drizzle's `{ mode: "timestamp" }` maps to a JS Date and what the dashboard contract reads.
 * Business-day logic is computed in the tenant timezone (default Asia/Tehran, no DST).
 * Weekdays use the Persian week: 0 = Saturday ... 6 = Friday.
 * Money: integer Toman (no decimals).
 * Ids: text holding a UUID v4, generated by the app so inserts never need a round trip.
 */
import { randomUUID } from "node:crypto";
import { relations, sql } from "drizzle-orm";
import {
  check,
  index,
  integer,
  primaryKey,
  sqliteTable,
  text,
  unique,
} from "drizzle-orm/sqlite-core";

