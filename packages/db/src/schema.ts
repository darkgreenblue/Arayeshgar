// ---------------------------------------------------------------------------
// Bookings.
//
// Postgres enforced "no two live bookings overlap for one barber" with an EXCLUDE
// constraint. SQLite has none, so the guarantee is rebuilt from two halves that are
// together at least as strong:
//
//   1. Every write goes through BEGIN IMMEDIATE (the default of @libsql/client's
//      transaction()), so a writer takes the single write lock before it reads.
//      Two processes therefore cannot both see the slot free — the second one waits
//      and then reads the first one's committed row.
//   2. `bookings_staff_start_uq`, a partial unique index over (staff_id, start_at)
//      restricted to live statuses, in 0001_constraints.sql. A backstop for the
//      exact-same-start case that holds even if a future caller forgets the lock.
//
// Partial overlap (09:00-09:30 against 09:15-09:45) is caught by the explicit
// overlap query that booking/create.ts runs inside that same transaction.
// ---------------------------------------------------------------------------
export const bookings = sqliteTable(
  "bookings",
  {
    id: id(),
    tenantId: text("tenant_id")
      .notNull()
      .references(() => tenants.id, { onDelete: "cascade" }),
    staffId: text("staff_id")
      .notNull()
      .references(() => staff.id, { onDelete: "restrict" }),
    customerId: text("customer_id")
      .notNull()
      .references(() => customers.id, { onDelete: "restrict" }),
    serviceId: text("service_id")
      .notNull()
      .references(() => services.id, { onDelete: "restrict" }),
    code: text("code").notNull(), // 6-char human code, unique per tenant
    startAt: integer("start_at", { mode: "timestamp" }).notNull(),
    endAt: integer("end_at", { mode: "timestamp" }).notNull(),
    status: text("status", { enum: BOOKING_STATUSES }).notNull(),
    source: text("source", { enum: BOOKING_SOURCES }).notNull(),
    priceSnapshot: integer("price_snapshot").notNull(),
    depositAmount: integer("deposit_amount").notNull().default(0),
    expiresAt: integer("expires_at", { mode: "timestamp" }), // for pending_payment
    notes: text("notes"),
    cancelledBy: text("cancelled_by"), // 'customer' | 'system' | user id
    cancelReason: text("cancel_reason"),
    reminder24hSentAt: integer("reminder_24h_sent_at", { mode: "timestamp" }),
    createdAt: integer("created_at", { mode: "timestamp" }).notNull().default(now()),
    updatedAt: integer("updated_at", { mode: "timestamp" }).notNull().default(now()),
  },
  (t) => [
    unique("bookings_tenant_code_uq").on(t.tenantId, t.code),
    index("bookings_staff_start_idx").on(t.staffId, t.startAt),
    index("bookings_tenant_start_idx").on(t.tenantId, t.startAt),
    index("bookings_customer_idx").on(t.customerId),
    index("bookings_status_expires_idx").on(t.status, t.expiresAt),
    check("bookings_status_ck", sql`${t.status} IN (${inList(BOOKING_STATUSES)})`),
    check("bookings_source_ck", sql`${t.source} IN (${inList(BOOKING_SOURCES)})`),
    check("bookings_span_ck", sql`${t.endAt} > ${t.startAt}`),
  ],
);

